-- Bo‘ston Go starter schema. Uses a boston_go_ prefix to avoid collisions
-- with other applications in a shared Supabase project.

create table if not exists public.boston_go_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  created_at timestamptz not null default now()
);

create table if not exists public.boston_go_categories (
  id bigint generated by default as identity primary key,
  name_uz text not null,
  slug text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.boston_go_stores (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references auth.users(id) on delete set null,
  name text not null,
  description text,
  category_id bigint references public.boston_go_categories(id),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.boston_go_products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.boston_go_stores(id) on delete cascade,
  name text not null,
  description text,
  price numeric(12,2) not null default 0 check (price >= 0),
  image_url text,
  is_available boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.boston_go_orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id) on delete cascade,
  store_id uuid references public.boston_go_stores(id) on delete set null,
  status text not null default 'new'
    check (status in ('new','accepted','preparing','on_the_way','completed','cancelled')),
  total numeric(12,2) not null default 0 check (total >= 0),
  delivery_address text,
  customer_phone text,
  created_at timestamptz not null default now()
);

create table if not exists public.boston_go_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.boston_go_orders(id) on delete cascade,
  product_id uuid references public.boston_go_products(id) on delete set null,
  product_name text not null,
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(12,2) not null default 0 check (unit_price >= 0)
);

alter table public.boston_go_profiles enable row level security;
alter table public.boston_go_categories enable row level security;
alter table public.boston_go_stores enable row level security;
alter table public.boston_go_products enable row level security;
alter table public.boston_go_orders enable row level security;
alter table public.boston_go_order_items enable row level security;

drop policy if exists "boston_go_profiles_select_own" on public.boston_go_profiles;
create policy "boston_go_profiles_select_own" on public.boston_go_profiles
for select to authenticated using (auth.uid() = id);
drop policy if exists "boston_go_profiles_insert_own" on public.boston_go_profiles;
create policy "boston_go_profiles_insert_own" on public.boston_go_profiles
for insert to authenticated with check (auth.uid() = id);
drop policy if exists "boston_go_profiles_update_own" on public.boston_go_profiles;
create policy "boston_go_profiles_update_own" on public.boston_go_profiles
for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "boston_go_categories_read" on public.boston_go_categories;
create policy "boston_go_categories_read" on public.boston_go_categories
for select to anon, authenticated using (true);

drop policy if exists "boston_go_stores_read_active" on public.boston_go_stores;
create policy "boston_go_stores_read_active" on public.boston_go_stores
for select to anon, authenticated using (is_active = true or auth.uid() = owner_id);
drop policy if exists "boston_go_stores_owner_insert" on public.boston_go_stores;
create policy "boston_go_stores_owner_insert" on public.boston_go_stores
for insert to authenticated with check (auth.uid() = owner_id);
drop policy if exists "boston_go_stores_owner_update" on public.boston_go_stores;
create policy "boston_go_stores_owner_update" on public.boston_go_stores
for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

drop policy if exists "boston_go_products_read_available" on public.boston_go_products;
create policy "boston_go_products_read_available" on public.boston_go_products
for select to anon, authenticated using (
  is_available = true or exists (
    select 1 from public.boston_go_stores s
    where s.id = store_id and s.owner_id = auth.uid()
  )
);
drop policy if exists "boston_go_products_owner_insert" on public.boston_go_products;
create policy "boston_go_products_owner_insert" on public.boston_go_products
for insert to authenticated with check (exists (
  select 1 from public.boston_go_stores s where s.id = store_id and s.owner_id = auth.uid()
));
drop policy if exists "boston_go_products_owner_update" on public.boston_go_products;
create policy "boston_go_products_owner_update" on public.boston_go_products
for update to authenticated using (exists (
  select 1 from public.boston_go_stores s where s.id = store_id and s.owner_id = auth.uid()
)) with check (exists (
  select 1 from public.boston_go_stores s where s.id = store_id and s.owner_id = auth.uid()
));

drop policy if exists "boston_go_orders_customer_read" on public.boston_go_orders;
create policy "boston_go_orders_customer_read" on public.boston_go_orders
for select to authenticated using (auth.uid() = customer_id);
drop policy if exists "boston_go_orders_customer_insert" on public.boston_go_orders;
create policy "boston_go_orders_customer_insert" on public.boston_go_orders
for insert to authenticated with check (auth.uid() = customer_id);
drop policy if exists "boston_go_order_items_customer_read" on public.boston_go_order_items;
create policy "boston_go_order_items_customer_read" on public.boston_go_order_items
for select to authenticated using (exists (
  select 1 from public.boston_go_orders o where o.id = order_id and o.customer_id = auth.uid()
));
drop policy if exists "boston_go_order_items_customer_insert" on public.boston_go_order_items;
create policy "boston_go_order_items_customer_insert" on public.boston_go_order_items
for insert to authenticated with check (exists (
  select 1 from public.boston_go_orders o where o.id = order_id and o.customer_id = auth.uid()
));

